#####################Variables##############################
# Variables are used for storing different types of values.
# Variables can have almost any name. 
# variable names can consist of letters and numbers, but they must start with a letter or "_". 
# "valtozoNev2" is a valid name, "2valtozoNev" isn't

# Here, I create a new variable called "x" with the value "Bob"
x = "Bob" 
# the equals sign is also called the assignment operator
# it's used to _give value_ to variables
x = 5
# Here, I _assigned_ a new value to x
# Now its value is 5, and its type is integer (sometimes written as int)
# Some variables with important data types:

x = 5               # Integer (int)

x = 5.5             # Floating-point number (float)

x = "Bob"           # String : a _string_ of characters

x = True            # Boolean variable : Its value can only be True or False)

x = [1,2,3,4,5]     # List : stores a list of items. the items can be any data type (even other lists)

# We can check the data type of any variable by using a function called type()
# the type() function takes the name of the variable as its _argument_
type(x)     # This line checks the data type of x
